import { writeFile } from "node:fs/promises";

/**
 * Writes `src/lib/scarab-tiers.ts`: which of the game's five rarity tiers each
 * scarab belongs to.
 *
 * The tier is the one thing that says how often a scarab is seen, and it is not
 * on the item, not in its name and not in its picture. The wiki carries it as a
 * tag, from GGG's own item data, and the Scarab article is explicit that the
 * art is no guide to it:
 *
 *   "Their drop rates are determined by one of five internal rarity tiers:
 *    Common, Uncommon, Rare, Mythic, and Extreme. Their artwork is not
 *    indicative of rarity tiers."
 *   https://www.poewiki.net/wiki/Scarab
 *
 * So nothing here reads a tier out of an icon path, and nothing should: the
 * pre-3.24 tier words (LesserScarab, GreaterScarab, Tier4Scarab) are still in
 * the art filenames and no longer mean anything. Abyss Scarab of Crystals and
 * Abyss Scarab of Descending are both rare and wear two different ones.
 *
 *   node scripts/fetch-scarab-tiers.mjs
 */

const WIKI = "https://www.poewiki.net/w/api.php";
const OUT = new URL("../src/lib/scarab-tiers.ts", import.meta.url);

/** Rarest last. A scarab carrying two of these is the rarer of them. */
const TIERS = ["common", "uncommon", "rare", "mythic", "extreme"];

// `tags` is a list field, so it takes HOLDS and throws on LIKE. And the default
// user agent gets through where a browser-like one is challenged.
const query = new URLSearchParams({
  action: "cargoquery",
  format: "json",
  tables: "items",
  fields: "items.name=name,items.tags=tags,items.drop_enabled=de",
  where: 'items.tags HOLDS "scarab"',
  limit: "500",
  order_by: "items.name",
});

const res = await fetch(`${WIKI}?${query}`);
if (!res.ok) throw new Error(`poewiki -> ${res.status}`);
const data = await res.json();
if (data.error) throw new Error(data.error.info);

const rows = (data.cargoquery ?? []).map((r) => r.title);
console.log(`${rows.length} scarabs on the wiki.`);

const tiers = [];
const untiered = [];
for (const row of rows) {
  // Anything that cannot drop any more is not a scarab this league has.
  if (row.de !== "1") continue;
  const tags = row.tags.split(",").map((t) => t.trim());
  const found = TIERS.filter((t) => tags.includes(`${t}_scarab`));
  if (found.length === 0) {
    untiered.push(row.name);
    continue;
  }
  tiers.push([row.name, found[found.length - 1]]);
}

if (untiered.length) {
  console.error(`No rarity tag:\n  ${untiered.join("\n  ")}`);
  process.exitCode = 1;
}

tiers.sort(([a], [b]) => a.localeCompare(b));
const counts = {};
for (const [, tier] of tiers) counts[tier] = (counts[tier] ?? 0) + 1;
console.log(`${tiers.length} that drop:`, counts);

const body = `// Generated by scripts/fetch-scarab-tiers.mjs. Do not edit by hand.
//
// Which of the game's five rarity tiers each scarab belongs to, from the tags
// the wiki carries out of GGG's item data. The tier is what decides how often
// one is seen, and it is on neither the item nor its art. See the script.

export type ScarabTier = ${TIERS.map((t) => `"${t}"`).join(" | ")};

/** Missing for a scarab this league added since the file was last written. */
export const SCARAB_TIERS: Readonly<Record<string, ScarabTier | undefined>> = {
${tiers.map(([name, tier]) => `  ${JSON.stringify(name)}: "${tier}",`).join("\n")}
};
`;

await writeFile(OUT, body);
console.log(`Wrote ${OUT.pathname}`);
