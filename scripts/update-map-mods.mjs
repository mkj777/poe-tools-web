import { writeFileSync } from "node:fs";

/**
 * Every modifier a map can roll, as the text the item shows.
 *
 * The stash search reads that text and nothing else useful, so this list is
 * both what the generator cuts fragments from and what it must avoid colliding
 * with. See docs/stash-search.md for the engine model.
 *
 * The query is narrower than it looks. `domain=5` is the area domain, which
 * carries far more than map affixes: Expedition logbook mods, Eagon mission
 * mods, Shaper influence, Labyrinth darkshrines. Restricting to generation
 * types 1 and 2 (prefix and suffix) cuts it to 799 rows, and dropping the
 * `MapCorruptedSideArea` family removes the Vaal side area rewards, which roll
 * on a Vaal vessel rather than on the map.
 */

const UA = "poe-tools-web/0.1 (contact: maxikie02@gmail.com)";

const WHERE = [
  "domain=5",
  "(generation_type=1 OR generation_type=2)",
  'id LIKE "Map%"',
  // "MapCorruptedSideArea" starts with "Map" too, so the family has to be named
  // separately. It is what carries the `Vaal Vessel contains …` rewards.
  'id NOT LIKE "MapCorruptedSideArea%"',
].join(" AND ");

const url =
  "https://www.poewiki.net/index.php?title=Special:CargoExport&format=json&limit=5000" +
  "&tables=mods&fields=id,name,stat_text&where=" +
  encodeURIComponent(WHERE);

const res = await fetch(url, { headers: { "User-Agent": UA } });
if (!res.ok) throw new Error(`cargo -> ${res.status}`);
const rows = await res.json();

/**
 * A number is written `12`, `(20-30)` or `+(20-30)` here and lands on the item
 * as whatever that tier rolled. A fragment must never contain one, so the whole
 * run collapses to a single `#` and the generator treats `#` as a place it may
 * not cross.
 */
const NUMBER = /[-+]?\(?[-+]?\d+(?:\.\d+)?(?:\s*[-–]\s*\d+(?:\.\d+)?)?\)?/g;

/**
 * Entities are escaped twice over: the row holds `&lt;br&gt;` as its line
 * separator and `&lt;span class="keyword"&gt;` around some keywords. So the
 * separator is split off first, then entities are decoded, and only then can
 * tags be stripped.
 */
const clean = (piece) =>
  piece
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/\[\[([^\]|]*\|)?([^\]]*)\]\]/g, "$2")
    .replace(/<[^>]+>/g, " ")
    .replace(/&#0?39;/g, "'")
    .replace(/&amp;/g, "&")
    .replace(/&quot;/g, '"')
    .replace(/&nbsp;/g, " ")
    .replace(/\s+/g, " ")
    .trim();

const lines = new Set();
for (const row of rows) {
  // The wiki breaks one long modifier across several pieces, and the game wraps
  // it in the tooltip too. They stay separate: a fragment spanning the break
  // could fail against a real line break.
  for (const piece of String(row["stat text"] ?? "").split("&lt;br&gt;")) {
    const text = clean(piece);
    if (!text) continue;
    // Marked hidden on the wiki because no tooltip prints it. What is not shown
    // cannot be searched, so it is neither a target nor a collision.
    if (/\(Hidden\)$/.test(text)) continue;
    lines.add(text.replace(NUMBER, "#").replace(/#\s*#/g, "#").trim());
  }
}

const sorted = [...lines].sort();
const body = sorted.map((line) => `  ${JSON.stringify(line)},`).join("\n");

writeFileSync(
  new URL("../src/lib/map-mods.ts", import.meta.url),
  `/**
 * Every display line a map modifier can put on a map, numbers replaced by \`#\`.
 *
 * Generated by \`pnpm mods:maps\` from the PoE wiki. Do not edit by hand.
 */
export const MAP_MOD_LINES: readonly string[] = [
${body}
];
`,
);

console.log(`${rows.length} rows -> ${sorted.length} distinct lines`);
